export function getCardHindiInfo(card: {
  key?: string;
  label?: string;
  title?: string;
  suit?: string;
  line?: string;
}): ICardHindiInfo {
  const key = card?.key || '';
  const label = card?.label || '';
  const title = card?.title || '';
  const suit = card?.suit || 'Dharma';
  const line = card?.line || '';

  // Direct key lookup
  if (CARD_HINDI_REGISTRY[key]) {
    return CARD_HINDI_REGISTRY[key];
  }

  // Fallback match by label or title
  for (const [regKey, meta] of Object.entries(CARD_HINDI_REGISTRY)) {
    if (
      label.toLowerCase() === regKey.toLowerCase() ||
      title.toLowerCase() === meta.title.toLowerCase() ||
      regKey.toLowerCase().includes(key.toLowerCase())
    ) {
      return meta;
    }
  }

  return {
    suit: SUIT_HINDI_NAMES[suit] || suit,
    label: label,
    title: title,
    line: line,
  };
}
